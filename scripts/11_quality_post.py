import json

import pandas as pd

from utils import PROCESSED, QUALITY, ensure_dirs

if __name__ == "__main__":
    ensure_dirs()
    df = pd.read_csv(PROCESSED / "county_period.csv", dtype={"fips": str})
    integ = json.loads((QUALITY / "integration_log.json").read_text())
    num = df.select_dtypes("number")
    r = {}
    r["completeness"] = {
        "rows": len(df), "counties": df["fips"].nunique(),
        "null_counts": {c: int(n) for c, n in df.isna().sum().items() if n},
        "counties_with_both_periods": int((df.groupby("fips")["period"].nunique() == 2).sum()),
        "population_share_covered_by_period": (df.groupby("period")["population"].sum() / 1e6).round(1).to_dict(),
        "join_losses": integ,
    }
    r["consistency"] = {
        "duplicate_fips_period": int(df.duplicated(["fips", "period"]).sum()),
        "invalid_fips": int((~df["fips"].str.fullmatch(r"\d{5}")).sum()),
        "negative_numeric_values": int((num < 0).sum().sum()),
        "renter_share_outside_0_1": int((~df["renter_share"].between(0, 1)).sum()),
        "unemp_rate_outside_0_100": int((~df["unemp_rate"].between(0, 100)).sum()),
    }
    corr = {p: round(g["zhvi_2024usd"].corr(g["acs_median_home_value_2024usd"]), 3) for p, g in df.groupby("period")}
    r["accuracy"] = {
        "corr_zillow_vs_acs_home_value_by_period": corr,
        "median_ratio_zillow_to_acs_home_value": round((df["zhvi_2024usd"] / df["acs_median_home_value_2024usd"]).median(), 3),
        "price_to_income_summary": df.groupby("period")["price_to_income"].describe().round(2).to_dict("index"),
        "price_to_income_gt_15_outliers": df.loc[df["price_to_income"] > 15, ["fips", "period", "acs_name", "price_to_income"]].head(20).to_dict("records"),
        "income_low_reliability_rows": int(df["income_low_reliability"].sum()),
    }
    r["timeliness"] = {
        "acs_vintages": ["2015-2019 (released Dec 2020)", "2020-2024 (released Jan 2026)"],
        "zillow_months_per_county": df.groupby("period")["zillow_months"].describe()[["min", "50%"]].to_dict("index"),
        "bls_years_per_county": df.groupby("period")["bls_years"].min().to_dict(),
        "rows_with_incomplete_zillow_period_lt_48_months": int((df["zillow_months"] < 48).sum()),
    }
    (QUALITY / "post_integration_report.json").write_text(json.dumps(r, indent=2, default=str))
    md = ["# Post-integration data quality report", "", "Generated by `scripts/11_quality_post.py` from `data/processed/county_period.csv`.", ""]
    for k, v in r.items():
        md += [f"## {k.title()}", "", "```json", json.dumps(v, indent=2, default=str), "```", ""]
    (QUALITY / "post_integration_report.md").write_text("\n".join(md))
    print(json.dumps({k: r[k] for k in ["consistency"]}, indent=2), r["accuracy"]["corr_zillow_vs_acs_home_value_by_period"])